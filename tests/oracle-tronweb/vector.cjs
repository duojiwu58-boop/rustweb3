// Public Trust Wallet test key ONLY. No user inputs, environment keys or RPC calls.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
let networkAttempts = 0;
const denyNetwork = () => { networkAttempts++; throw new Error('Oracle must remain offline'); };
for (const name of ['node:http', 'node:https']) {
  const module = require(name); module.request = denyNetwork; module.get = denyNetwork;
}
require('node:net').Socket.prototype.connect = denyNetwork;
require('node:tls').connect = denyNetwork;
globalThis.fetch = denyNetwork;
const utils = require('tronweb/utils').default;
const publicTestKey = '2d8f68944bdbfbc0769542fba8fc2d2a3de67393334471624364c7006da2aa54';
const owner = 'TJRyWwFs9wTFGZg3JbrVriFbNfCug5tDeC';
const recipient = 'TW1dU4L3eNm7Lw8WvieLKEHpXWAussRG9Z';
const contract = 'THTR75o8xXAgCTQqpiot2AFRAjvW1tSbVV'; // Fictional token; NOT USDT.
assert.equal(utils.crypto.pkToAddress(publicTestKey), owner);
const calldata = 'a9059cbb' + utils.abi.encodeParams(['address','uint256'], [recipient,'1000']).slice(2);
const tx = { visible: false, raw_data: {
  ref_block_bytes: '7b3b', ref_block_hash: 'b21ace8d6ac20e7e',
  timestamp: 1539295479000, expiration: 1539331479000, fee_limit: 100000000,
  contract: [{ type: 'TriggerSmartContract', parameter: {
    type_url: 'type.googleapis.com/protocol.TriggerSmartContract',
    value: { owner_address: utils.address.toHex(owner), contract_address: utils.address.toHex(contract), data: calldata }
  } }]
} };
const pb = utils.transaction.txJsonToPb(tx);
tx.raw_data_hex = utils.transaction.txPbToRawDataHex(pb).toLowerCase();
tx.txID = utils.transaction.txPbToTxID(pb).replace(/^0x/, '').toLowerCase();
const signed = utils.crypto.signTransaction(publicTestKey, tx);
const sdkSignature = signed.signature[0].toLowerCase();
// TronWeb ECKeySign returns recovery + 27. Our wire convention is 0/1.
const recovery = parseInt(sdkSignature.slice(-2), 16);
assert.ok(recovery === 27 || recovery === 28);
const signature = sdkSignature.slice(0, -2) + (recovery - 27).toString(16).padStart(2, '0');
const ownerHex = utils.address.toHex(owner).toLowerCase();
assert.equal(utils.crypto.ecRecover(tx.txID, sdkSignature).toLowerCase(), ownerHex);
pb.addSignature(Buffer.from(signature, 'hex'));
const values = {
  oracle: 'tronweb-6.5.1',
  owner_hex: ownerHex,
  calldata,
  raw_data_hex: tx.raw_data_hex,
  txid: tx.txID,
  sdk_signature: sdkSignature,
  signature,
  signed_hex: Buffer.from(pb.serializeBinary()).toString('hex')
};
const fixture = '# PUBLIC TEST VECTOR; never fund these addresses. Generated by vector.cjs.\n' +
  Object.entries(values).map(([key,value]) => `${key}=${value}`).join('\n') + '\n';
const target = path.join(__dirname, '..', 'fixtures', 'trc20-tronweb-6.5.1.txt');
if (process.argv.includes('--write')) fs.writeFileSync(target, fixture, 'utf8');
else assert.equal(fs.readFileSync(target, 'utf8'), fixture, 'Oracle fixture changed');
assert.equal(networkAttempts, 0);
console.log('PASS: TronWeb ABI, protobuf raw/signed bytes, txID, signature and owner; zero network attempts');
